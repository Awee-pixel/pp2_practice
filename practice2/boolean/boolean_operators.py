#Operators are used to perform operations on variables and values.

#In the example below, we use the + operator to add together two values:
print(10 + 5)

#one of main boolean operatots is 'and' or '&&' in C
#results is true only if both conditions are true

x = 5
print(x > 3 and x < 10)  # True

#the next one is 'or' or '||' in C
#result is true if at least one condition is true

x = 5
print(x < 3 or x < 10)  # True

#the last one is 'not' or '!'
#reverse the value(true->false, false->true)

is_raining = False
print(not is_raining)  # True
